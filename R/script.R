new_step <- function(fn, ...) list(fn = fn, args = rlang::list2(...))

run_ma_step <- function(data, step, files = NULL) {
  args <- step$args
  if (!is.null(args$path) && !is.null(files[[args$path]])) args$path <- files[[args$path]]
  call <- rlang::call2(step$fn, data, !!!args)
  eval(call, envir = asNamespace("bayesmaDatR"))
}

merge_edit_steps <- function(steps) {
  purrr::reduce(steps, \(merged, step) {
    last <- if (length(merged)) merged[[length(merged)]] else list(fn = "")
    if (step$fn == "edit_ma_cells" && last$fn == "edit_ma_cells" && identical(last$args[[1]], step$args[[1]])) {
      for (nm in c("row", "column", "value")) last$args[[nm]] <- c(last$args[[nm]], step$args[[nm]])
      merged[[length(merged)]] <- last
      merged
    } else {
      c(merged, list(step))
    }
  }, .init = list())
}

format_ma_script <- function(steps, export = NULL, date = Sys.Date(), data_dir = ".") {
  steps <- merge_edit_steps(steps)
  files <- unique(unlist(purrr::map(steps, \(s) s$args$path)))
  steps <- purrr::map(steps, \(s) {
    if (!is.null(s$args$path) && s$fn != "import_ma_data") s$args$path <- path_expr(s$args$path)
    s
  })
  header <- c(
    paste0("# Generated by the bayesmaDatR data manager on ", format(date), " (bayesmaDatR ",
           utils::packageVersion("bayesmaDatR"), ")."),
    "# Repeats every import and edit made in the app, in order. Rows are numbered",
    "# as they were in the app's tables at the time of each edit.",
    "",
    "library(bayesmaDatR)",
    if (length(files)) data_dir_lines(data_dir, files),
    "",
    "data <- template_ma_data()"
  )

  n_spec <- 0L
  pending <- list()
  body <- character()
  flush <- function() {
    if (length(pending)) body <<- c(body, "", "data <- data |>", pending_pipe(pending))
    pending <<- list()
  }
  for (step in steps) {
    if (step$fn == "import_ma_data") {
      flush()
      n_spec <- n_spec + 1L
      name <- paste0("spec_", n_spec)
      body <- c(body, "", paste(name, "<-", deparse_value(step$args$spec)),
                paste0("data <- data |> import_ma_data(", expr_text(path_expr(step$args$path)), ", ", name, ")"))
    } else {
      pending <- c(pending, list(deparse_call(step)))
    }
  }
  flush()

  export_lines <- if (!is.null(export)) {
    c("", "analysis_data <- data |>", pending_pipe(list(deparse_call(export))))
  }
  c(header, body, export_lines, "")
}

pending_pipe <- function(calls) {
  purrr::imap(calls, \(lines, i) {
    lines <- paste0("  ", lines)
    if (i < length(calls)) lines[length(lines)] <- paste(lines[length(lines)], "|>")
    lines
  }) |>
    unlist()
}

deparse_call <- function(step) {
  args <- purrr::map(step$args, \(x) if (is.atomic(x)) str2lang(deparse_atomic(x)) else x)
  fn <- if (grepl("::", step$fn, fixed = TRUE)) str2lang(step$fn) else step$fn
  rlang::expr_deparse(rlang::call2(fn, !!!args), width = 90)
}

deparse_atomic <- function(x) paste(deparse(x, width.cutoff = 500L), collapse = " ")

deparse_value <- function(x, indent = 0L) {
  if (!is.list(x)) return(deparse_atomic(x))
  if (!length(x)) return("list()")
  pad <- strrep("  ", indent + 1L)
  nms <- names(x) %||% rep("", length(x))
  items <- purrr::map2_chr(x, nms, \(value, nm) {
    if (nzchar(nm) && make.names(nm) != nm) nm <- paste0("`", nm, "`")
    paste0(pad, if (nzchar(nm)) paste0(nm, " = "), deparse_value(value, indent + 1L))
  })
  paste0("list(\n", paste(items, collapse = ",\n"), "\n", strrep("  ", indent), ")")
}

path_expr <- function(path) rlang::call2("file.path", rlang::sym("data_dir"), path)

data_dir_lines <- function(data_dir, files) {
  data_dir <- gsub("\\\\", "/", trimws(data_dir %||% ""))
  if (!nzchar(data_dir)) data_dir <- "."
  c("",
    paste0("# Folder holding ", paste(files, collapse = ", "), if (data_dir == ".") " (\".\" is the working directory)"),
    paste("data_dir <-", deparse_atomic(data_dir)))
}
