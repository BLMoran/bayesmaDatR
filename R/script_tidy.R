format_tidy_script <- function(steps, export = NULL, files = list(), date = Sys.Date(), data_dir = ".") {
  states <- purrr::accumulate(steps, \(data, step) run_ma_step(data, step, files), .init = template_ma_data())
  ctx <- new.env(parent = emptyenv())
  ctx$files <- files
  ctx$defined <- character()
  ctx$columns <- list()
  ctx$sheets <- list()
  ctx$raws <- collect_raws(steps, ctx)

  paths <- unique(purrr::map_chr(ctx$raws, "path"))
  header <- c(
    paste0("# Generated by the bayesmaDatR data manager on ", format(date), " (bayesmaDatR ",
           utils::packageVersion("bayesmaDatR"), ")."),
    "# Tidyverse version of the imports and edits made in the app. Only the last",
    "# two steps need bayesmaDatR.",
    if (length(paths)) data_dir_lines(data_dir, paths)
  )
  imports <- if (length(ctx$raws)) c("", "# Import data", unlist(purrr::map(ctx$raws, raw_lines)))

  timeline <- list()
  interleaved <- FALSE
  for (k in seq_along(steps)) {
    step <- steps[[k]]
    if (step$fn == "import_ma_data") {
      if (purrr::some(timeline, \(t) t$kind == "op")) interleaved <- TRUE
      timeline <- c(timeline, list(list(kind = "chunks", value = tidy_import(step, states[[k]], states[[k + 1]], ctx))))
    } else {
      op <- tidy_op(step, states[[k]], states[[k + 1]], ctx)
      if (!is.null(op)) timeline <- c(timeline, list(list(kind = "op", value = op)))
    }
  }
  chunks <- purrr::keep(timeline, \(t) t$kind == "chunks") |> purrr::map("value") |> purrr::list_flatten()
  ops <- purrr::keep(timeline, \(t) t$kind == "op") |> purrr::map("value")
  body <- if (!interleaved) {
    c(section_lines(chunks, ctx, drop_replaced = TRUE), if (length(ops)) emit_ops(ops, ctx))
  } else {
    runs <- cumsum(c(TRUE, purrr::map_chr(timeline[-1], "kind") != purrr::map_chr(timeline[-length(timeline)], "kind")))
    unlist(purrr::map(split(timeline, runs), \(run) {
      values <- purrr::map(run, "value")
      if (run[[1]]$kind == "op") emit_ops(values, ctx) else section_lines(purrr::list_flatten(values), ctx)
    }))
  }

  tables <- intersect(c("studies", "outcomes", "risk_of_bias", "inspect_sr"), ctx$defined)
  combine <- if (length(tables)) {
    c("", "# Combine the sections", "ma_data <- bayesmaDatR::new_ma_data(",
      paste0("  ", tables, " = ", table_var(tables), c(rep(",", length(tables) - 1), "")), ")")
  } else {
    c("", "# Nothing has been entered yet", "ma_data <- bayesmaDatR::new_ma_data()")
  }
  per_outcome <- outcome_export_lines(states[[length(states)]], export, reserved = c(
    "dat", "studies", "outcomes", "dat_rob", "inspect_sr", "ma_data", "rob_new", "dat_outcomes",
    purrr::map_chr(ctx$raws, "name")
  ))
  combine <- c(combine, per_outcome$lines)
  result <- per_outcome$result %||% "ma_data"
  structure(c(header, imports, body, combine, ""), result = result)
}

section_lines <- function(chunks, ctx, drop_replaced = FALSE) {
  order <- c("studies", "outcomes", "risk_of_bias", "inspect_sr")
  unlist(purrr::map(order, \(sec) {
    mine <- purrr::keep(chunks, \(ch) ch$section == sec)
    if (drop_replaced && length(mine)) {
      last <- max(c(1, which(purrr::map_lgl(mine, "replace"))))
      mine <- mine[seq(last, length(mine))]
    }
    unlist(purrr::map(mine, "lines"))
  }))
}

chunk <- function(section, lines, replace) list(section = section, lines = lines, replace = replace)

bind_rows_lines <- function(target, items) {
  body <- purrr::imap(items, \(item, i) {
    code <- item$code
    if (i < length(items)) code[length(code)] <- paste0(code[length(code)], ",")
    paste0("  ", c(if (!is.null(item$comment)) paste("#", item$comment), code))
  })
  c(paste(target, "<- dplyr::bind_rows("), unlist(body), ")")
}

outcome_export_lines <- function(data, export, reserved) {
  out <- data$outcomes
  ids <- unique(out$outcome_id[!is.na(out$outcome_id)])
  if (!length(ids)) return(list(lines = character(), result = NULL))
  fn <- export$fn %||% "as_bayesma"
  shared <- export$args[setdiff(names(export$args), c("outcome", "timepoint", "measure"))]
  wide <- fn == "as_MetaStan" || !identical(shared$format, "long")

  calls <- if (!is.null(export)) list(list(name = "dat_outcomes", label = export$args$outcome, args = export$args))
  for (id in ids) {
    timepoints <- unique(out$timepoint[out$outcome_id %in% id & !is.na(out$timepoint)])
    split_timepoints <- wide && length(timepoints) > 1
    for (tp in if (split_timepoints) timepoints else list(NULL)) {
      name <- paste0("dat_", snake_name(paste(c(id, tp), collapse = "_")))
      calls <- c(calls, list(list(name = name, label = c(id, tp), args = c(list(outcome = id, timepoint = tp), shared))))
    }
  }
  names <- purrr::map_chr(calls, "name")
  clash <- names %in% setdiff(reserved, "dat_outcomes") | (names == "dat_outcomes" & seq_along(names) > 1)
  names[clash] <- paste0(names[clash], "_data")
  names <- make.unique(names, sep = "_")

  lines <- purrr::map2(calls, names, \(cl, nm) {
    step <- list(fn = fn, args = purrr::compact(cl$args))
    ok <- tryCatch({
      suppressWarnings(suppressMessages(run_ma_step(data, step)))
      TRUE
    }, error = \(e) cli::ansi_strip(conditionMessage(e)))
    step$fn <- paste0("bayesmaDatR::", fn)
    code <- c(paste(nm, "<- ma_data |>"), paste0("  ", deparse_call(step)))
    if (!isTRUE(ok)) {
      code <- c(paste0("# Could not be prepared in the app: ", gsub("\n", " ", ok)), paste("#", code))
    }
    heading <- if (length(cl$label) == 2 && nm != "dat_outcomes") paste(cl$label, collapse = " at ") else paste(cl$label, collapse = ", ")
    c("", paste("# Outcome data:", heading), code)
  })
  list(lines = unlist(lines), result = if (!is.null(export)) names[1])
}

id_fields <- function(columns) {
  ids <- columns[c("study_id", "author", "year")]
  stats::setNames(ids, c("study_id", "author", "year")) |> purrr::compact()
}

cluster_fields <- function() c("n_clusters", "n_periods", "rho_w", "rho_b", "rho_wp")

collect_raws <- function(steps, ctx) {
  uses <- purrr::map(steps, \(s) {
    if (s$fn == "import_ma_data") {
      spec <- s$args$spec
      sections <- c(purrr::imap(spec[setdiff(names(spec), "outcomes")], \(x, sec) c(x, section = sec)),
                    purrr::map(spec$outcomes, \(x) c(x, section = "outcomes")))
      purrr::map(sections, \(x) list(path = s$args$path, sheet = x$sheet, header_row = x$header_row %||% 1,
                                     section = x$section, as_is = isTRUE(x$as_is),
                                     ids = id_fields(x$columns), columns = x$columns, extra = x$extra))
    } else if (s$fn == "import_study_column") {
      keys <- as.list(s$args$keys %||% c(study_id = "study_id"))
      list(list(path = s$args$path, sheet = s$args$sheet %||% 1, header_row = s$args$header_row %||% 1,
                section = "column", as_is = FALSE, ids = id_fields(keys)))
    }
  }) |>
    purrr::compact() |>
    purrr::list_flatten()
  if (!length(uses)) return(list())

  keys <- purrr::map_chr(uses, raw_key)
  raws <- uses[!duplicated(keys)]
  many_files <- length(unique(purrr::map_chr(raws, "path"))) > 1
  base <- purrr::map_chr(raws, \(r) {
    sheet <- if (is.numeric(r$sheet)) paste0("sheet", r$sheet) else r$sheet
    parts <- c(if (many_files) tools::file_path_sans_ext(r$path), sheet)
    paste0("dat_", snake_name(paste(parts, collapse = "_")))
  })
  clash <- base %in% c("dat_outcomes", "dat_rob")
  base[clash] <- paste0(base[clash], "_sheet")
  names <- if (length(raws) == 1) "dat" else make.unique(base, sep = "_")

  purrr::map2(raws, names, \(r, nm) {
    mine <- uses[keys == raw_key(r)]
    mapped <- purrr::discard(mine, "as_is")
    studies <- purrr::keep(mapped, \(u) u$section == "studies")
    study <- if (length(studies)) studies[[length(studies)]]
    ids <- if (!is.null(study)) study$ids else if (length(mapped)) mapped[[1]]$ids else list()
    same_ids <- all(purrr::map_lgl(mapped, \(u) identical(u$ids, ids)))
    info <- list(path = r$path, sheet = r$sheet, header_row = r$header_row, name = nm,
                 ids = ids, wrangle = length(mapped) > 0 && length(ids) > 0, filtered = same_ids,
                 study = study$columns, extra = study$extra, renames = character())
    columns <- if (!is.null(ctx$files[[r$path]])) names(sheet_data(ctx, r$path, r$sheet, r$header_row))
    for (field in c("author", "year")) {
      from <- ids[[field]]
      if (length(from) == 1 && from != field && !field %in% columns) info$renames[[from]] <- field
    }
    info
  }) |>
    stats::setNames(purrr::map_chr(raws, raw_key))
}

raw_lines <- function(r) {
  read <- read_raw_lines(r)
  stages <- if (isTRUE(r$wrangle)) wrangle_stages(r)
  lines <- c(paste(r$name, "<-", read[1]), read[-1])
  if (!length(stages)) return(lines)
  lines[length(lines)] <- paste(lines[length(lines)], "|>")
  body <- purrr::imap(stages, \(s, i) {
    s <- paste0("  ", unlist(strsplit(paste(s, collapse = "\n"), "\n")))
    if (i < length(stages)) s[length(s)] <- paste(s[length(s)], "|>")
    s
  })
  c(lines, unlist(body))
}

wrangle_stages <- function(r) {
  stages <- list()
  if (length(r$renames)) {
    stages <- c(stages, list(paste0("dplyr::rename(", paste(sym_text(r$renames), "=", sym_text(names(r$renames)),
                                                        collapse = ", "), ")")))
  }
  stages <- c(stages, list(paste0("dplyr::mutate(study_id = ", expr_text(id_expr(r$ids, r$renames), 60), ")")))
  if (r$filtered) stages <- c(stages, list("dplyr::filter_out(is.na(study_id))"))
  ids <- c("study_id", purrr::map_chr(r$ids[c("author", "year")] |> purrr::compact(), \(x) rename_sources(x, r$renames)[1]))
  fields <- setdiff(names(template_ma_data()$studies), c("study_id", "author", "year", cluster_fields()))
  study_cols <- c(unlist(r$study[fields]), r$extra, unlist(r$study[cluster_fields()]))
  order <- unique(c(ids, rename_sources(study_cols, r$renames)))
  c(stages, list(flow_text(paste0("dplyr::relocate(", paste(sym_text(order), collapse = ", "), ")"))))
}

flow_text <- function(text, width = 72) {
  pieces <- strsplit(text, "(?<=, )", perl = TRUE)[[1]]
  lines <- purrr::reduce(pieces[-1], \(acc, piece) {
    last <- acc[length(acc)]
    if (nchar(last) + nchar(piece) <= width) c(acc[-length(acc)], paste0(last, piece)) else c(acc, paste0("  ", piece))
  }, .init = pieces[1])
  paste(trimws(lines, "right"), collapse = "\n")
}

raw_key <- function(r) paste(r$path, r$sheet, r$header_row %||% 1, sep = "\r")

snake_name <- function(x) {
  x <- normalise_column_name(x)
  if (!nzchar(x) || grepl("^[0-9]", x)) x <- paste0("x", x)
  x
}

read_raw_lines <- function(r) {
  ext <- tolower(tools::file_ext(r$path))
  skip <- r$header_row - 1
  read <- switch(ext,
    xls = , xlsx = rlang::call2(quote(readxl::read_excel), path_expr(r$path), sheet = r$sheet,
                                skip = if (skip > 0) skip, col_types = "text"),
    csv = rlang::call2(str2lang("readr::read_csv"), path_expr(r$path), skip = if (skip > 0) skip,
                       col_types = str2lang('readr::cols(.default = "c")')),
    rds = if (identical(r$sheet, tools::file_path_sans_ext(r$path))) {
      rlang::call2("readRDS", path_expr(r$path))
    } else {
      rlang::call2("[[", rlang::call2("readRDS", path_expr(r$path)), r$sheet)
    },
    rda = , rdata = rlang::expr(local({
      load(!!path_expr(r$path))
      get(!!r$sheet)
    }))
  )
  read <- drop_null_args(read)
  c(paste(paste(rlang::expr_deparse(read, width = 500L), collapse = " "), "|>"), "  utils::type.convert(as.is = TRUE)")
}

drop_null_args <- function(call) {
  if (!rlang::is_call(call)) return(call)
  args <- rlang::call_args(call)
  rlang::call2(call[[1]], !!!purrr::compact(args))
}

raw_info <- function(ctx, path, sheet, header_row) {
  ctx$raws[[raw_key(list(path = path, sheet = sheet, header_row = header_row %||% 1))]]
}

sheet_data <- function(ctx, path, sheet, header_row) {
  key <- raw_key(list(path = path, sheet = sheet, header_row = header_row %||% 1))
  if (is.null(ctx$sheets[[key]])) {
    file <- ctx$files[[path]] %||% path
    raw <- read_upload_sheets(file, path)[[sheet]]
    ctx$sheets[[key]] <- sheet_from_raw(raw, header_row %||% 1)
  }
  ctx$sheets[[key]]
}

rename_sources <- function(sources, renames = character()) {
  hit <- sources %in% names(renames)
  sources[hit] <- renames[sources[hit]]
  unname(sources)
}

src_expr <- function(sources, renames = character()) {
  sources <- unique(rename_sources(sources, renames))
  if (!length(sources)) return(NULL)
  syms <- rlang::syms(sources)
  if (length(syms) == 1) syms[[1]] else rlang::call2(quote(dplyr::coalesce), !!!syms)
}

id_expr <- function(columns, renames = character()) {
  author <- src_expr(columns$author, renames)
  year <- src_expr(columns$year, renames)
  built <- if (is.null(author)) {
    NULL
  } else if (is.null(year)) {
    author
  } else {
    rlang::expr(dplyr::case_when(is.na(!!author) ~ NA, is.na(!!year) ~ !!author, .default = paste(!!author, !!year)))
  }
  given <- src_expr(columns$study_id, renames)
  if (is.null(given)) return(built %||% NA_character_)
  if (is.null(built)) return(given)
  rlang::expr(dplyr::coalesce(as.character(!!given), !!built))
}

section_id_expr <- function(r, ids) {
  if (isTRUE(r$wrangle) && identical(ids, r$ids)) rlang::sym("study_id") else id_expr(ids, r$renames)
}

rob_recode_stage <- function(domains, values, tool) {
  values <- unique(stats::na.omit(as.character(values)))
  to <- standardise_judgement(values, tool)
  change <- !is.na(to) & to != values
  if (!length(domains) || !any(change)) return(NULL)
  from <- values[change]
  to <- to[change]
  order <- order(match(to, rob_judgements(tool)), from)
  pairs <- paste0(purrr::map_chr(from[order], deparse_atomic), " ~ ", purrr::map_chr(to[order], deparse_atomic))
  cols <- if (length(domains) == 1) sym_text(domains) else paste0(sym_text(domains[1]), ":", sym_text(domains[length(domains)]))
  c(paste0("dplyr::mutate(dplyr::across(", cols, ", \\(x) dplyr::replace_values("),
    "  x,",
    paste0("  ", pairs, c(rep(",", length(pairs) - 1), "")),
    ")))")
}

recode_expr <- function(source, values, standardise) {
  if (is.null(source)) return(NULL)
  values <- unique(stats::na.omit(as.character(values)))
  to <- standardise(values)
  change <- !is.na(to) & to != values
  if (!any(change)) return(source)
  pairs <- purrr::map2(values[change], to[change], \(from, to) rlang::call2("~", from, to))
  rlang::call2(quote(dplyr::replace_values), source, !!!pairs)
}

section_stages <- function(r, ids, args, distinct = NULL) {
  keep_ids <- !(isTRUE(r$wrangle) && r$filtered && identical(ids, r$ids))
  c(list(transmute_lines(args)),
    if (keep_ids) list("dplyr::filter_out(is.na(study_id))"),
    if (!is.null(distinct)) list(paste0("dplyr::distinct(", distinct, ", .keep_all = TRUE)")))
}

tidy_import <- function(step, before, after, ctx) {
  spec <- step$args$spec
  path <- step$args$path
  out <- list()
  raw_for <- \(s) raw_info(ctx, path, s$sheet, s$header_row)
  data_for <- \(s) if (!is.null(ctx$files[[path]])) sheet_data(ctx, path, s$sheet, s$header_row)

  as_is <- purrr::keep(spec, \(s) isTRUE(s$as_is))
  for (sec in names(as_is)) {
    out <- c(out, list(chunk(sec, c("", paste0("# ", section_label(sec), " (used as-is)"),
                                   paste(sec, "<-", raw_for(as_is[[sec]])$name)), replace = TRUE)))
    ctx$columns[sec] <- list(names(data_for(as_is[[sec]])))
    ctx$defined <- union(ctx$defined, sec)
  }
  spec <- spec[!names(spec) %in% names(as_is)]

  if (!is.null(spec$studies)) {
    s <- spec$studies
    r <- raw_for(s)
    cols <- s$columns
    src <- \(field) src_expr(cols[[field]], r$renames)
    fields <- setdiff(names(template_ma_data()$studies), c("study_id", "author", "year", cluster_fields()))
    args <- c(list(study_id = section_id_expr(r, id_fields(cols)), author = src("author"), year = src("year")),
              purrr::map(stats::setNames(fields, fields), src))
    if (!is.null(args$trial_design)) {
      values <- mapped_column(data_for(s) %||% data.frame(), cols$trial_design)
      args$trial_design <- recode_expr(args$trial_design, values, normalise_trial_design)
    }
    extra <- setdiff(s$extra, names(args))
    args <- c(purrr::compact(args), rlang::syms(stats::setNames(extra, extra)),
              purrr::compact(purrr::map(stats::setNames(cluster_fields(), cluster_fields()), src)))
    ctx$columns$studies <- names(args)
    out <- c(out, list(chunk("studies", c("", "# Study details",
             assign_pipe("studies", r$name, section_stages(r, id_fields(cols), args, "study_id"))), replace = TRUE)))
    ctx$defined <- union(ctx$defined, "studies")
  }

  blocks <- spec$outcomes
  if (length(blocks)) {
    defined <- "outcomes" %in% ctx$defined
    items <- purrr::imap(blocks, \(b, i) {
      stages <- outcome_stages(b, raw_for(b), ctx)
      list(comment = b$outcome_id %||% paste("outcome block", i), code = assign_pipe(NULL, raw_for(b)$name, stages),
           columns = attr(stages, "columns"))
    })
    new_columns <- unique(unlist(purrr::map(items, "columns")))
    ctx$columns$outcomes <- if (defined) union(ctx$columns$outcomes, new_columns) else new_columns
    lines <- if (length(items) == 1 && !defined) {
      c("", paste("# Outcomes:", items[[1]]$comment), paste("outcomes <-", items[[1]]$code[1]), items[[1]]$code[-1])
    } else {
      replaced <- intersect(before$outcomes$outcome_id, block_outcome_ids(blocks, data_for))
      existing <- if (defined) {
        list(code = if (length(replaced)) {
          rlang::expr_deparse(rlang::expr(dplyr::filter_out(!!rlang::sym("outcomes"), outcome_id %in% !!replaced)),
                              width = 76)
        } else {
          "outcomes"
        })
      }
      heading <- if (defined) "# More outcomes" else "# Outcomes"
      c("", heading, bind_rows_lines("outcomes", c(if (!is.null(existing)) list(existing), items)))
    }
    out <- c(out, list(chunk("outcomes", lines, replace = !defined)))
    ctx$defined <- union(ctx$defined, "outcomes")
  }

  if (!is.null(spec$risk_of_bias)) {
    s <- spec$risk_of_bias
    r <- raw_for(s)
    cols <- s$columns
    df <- data_for(s)
    tool <- s$tool
    outcome_id <- src_expr(cols$outcome_id, r$renames)
    level <- src_expr(cols$rob_level, r$renames)
    default_level <- if (is.null(outcome_id)) "study" else rlang::expr(dplyr::if_else(is.na(outcome_id), "study", "outcome"))
    author <- src_expr(cols$author, r$renames)
    year <- src_expr(cols$year, r$renames)
    args <- list(study_id = section_id_expr(r, id_fields(cols)), author = author, year = year,
                 outcome_id = outcome_id, rob_tool = tool,
                 rob_level = if (is.null(level)) default_level else rlang::expr(dplyr::coalesce(tolower(!!level), !!default_level)))
    from_studies <- intersect(setdiff(c("author", "year"), names(purrr::compact(args))), ctx$columns$studies)
    add_names <- if (length(from_studies)) {
      c(paste0("dplyr::left_join(dplyr::select(studies, study_id, ", paste(from_studies, collapse = ", "),
               "), by = dplyr::join_by(study_id))"),
        paste0("dplyr::relocate(", paste(from_studies, collapse = ", "), ", .after = study_id)"))
    }
    domains <- intersect(rob_domains(tool), names(cols))
    for (d in domains) args[[d]] <- src_expr(cols[[d]], r$renames)
    values <- if (!is.null(df)) unlist(purrr::map(domains, \(d) mapped_column(df, cols[[d]])))
    recode <- rob_recode_stage(domains, values, tool)
    args <- purrr::compact(args)
    keys <- if (is.null(outcome_id)) "study_id, rob_level" else "study_id, outcome_id, rob_level"
    target <- if ("risk_of_bias" %in% ctx$defined && nrow(before$risk_of_bias)) "rob_new" else "dat_rob"
    ctx$columns$risk_of_bias <- union(if (target == "rob_new") ctx$columns$risk_of_bias, c(names(args), from_studies))
    lines <- c("", paste0("# Risk of bias (", tool, ")"),
               assign_pipe(target, r$name, append(section_stages(r, id_fields(cols), args, keys),
                                                  c(as.list(add_names), if (!is.null(recode)) list(recode)), after = 1)))
    if (target == "rob_new") {
      kept <- if (any(before$risk_of_bias$rob_tool %in% tool)) {
        paste0("dplyr::filter_out(dat_rob, rob_tool == ", deparse_atomic(tool), ")")
      } else {
        "dat_rob"
      }
      lines <- c(lines, paste0("dat_rob <- dplyr::bind_rows(", kept, ", rob_new)"))
    }
    out <- c(out, list(chunk("risk_of_bias", lines, replace = target == "dat_rob")))
    ctx$defined <- union(ctx$defined, "risk_of_bias")
  }

  if (!is.null(spec$inspect_sr)) {
    s <- spec$inspect_sr
    r <- raw_for(s)
    cols <- s$columns
    fields <- setdiff(inspect_sr_columns(), c("study_id", "author", "year"))
    args <- c(list(study_id = section_id_expr(r, id_fields(cols)), author = src_expr(cols$author, r$renames),
                   year = src_expr(cols$year, r$renames)),
              purrr::map(stats::setNames(fields, fields), \(f) src_expr(cols[[f]], r$renames)))
    args <- purrr::compact(args)
    ctx$columns$inspect_sr <- names(args)
    out <- c(out, list(chunk("inspect_sr", c("", "# INSPECT-SR",
             assign_pipe("inspect_sr", r$name, section_stages(r, id_fields(cols), args, "study_id"))), replace = TRUE)))
    ctx$defined <- union(ctx$defined, "inspect_sr")
  }

  new_studies <- after$studies[!after$studies$study_id %in% c(before$studies$study_id, study_ids_from(spec$studies, data_for)), ,
                               drop = FALSE]
  if (nrow(new_studies)) {
    sections <- c(spec[setdiff(names(spec), "outcomes")], spec$outcomes)
    raws <- unique(purrr::map(sections, raw_for))
    from_dat <- !"studies" %in% ctx$defined && length(raws) == 1 && isTRUE(raws[[1]]$wrangle) &&
      raws[[1]]$filtered && length(raws[[1]]$ids$author)
    lines <- if (from_dat) {
      r <- raws[[1]]
      args <- purrr::compact(list(study_id = rlang::sym("study_id"), author = src_expr(r$ids$author, r$renames),
                                  year = src_expr(r$ids$year, r$renames)))
      assign_pipe("studies", r$name, list(transmute_lines(args), "dplyr::distinct(study_id, .keep_all = TRUE)"))
    } else {
      rows <- tibble_call(new_studies[intersect(c("study_id", "author", "year"), names(new_studies))])
      if ("studies" %in% ctx$defined) {
        assign_pipe("studies", "studies", list(c("dplyr::bind_rows(", paste0("  ", rows), ")")))
      } else {
        c(paste("studies <-", rows[1]), rows[-1])
      }
    }
    out <- c(out, list(chunk("studies", c("", "# Studies named only in other sections", lines),
                             replace = !"studies" %in% ctx$defined)))
    ctx$defined <- union(ctx$defined, "studies")
    ctx$columns$studies <- union(ctx$columns$studies, c("study_id", "author", "year"))
  }
  out
}

