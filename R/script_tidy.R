outcome_stages <- function(b, r, ctx) {
  cols <- b$columns
  study <- r$study %||% list()
  src <- \(sources) src_expr(sources, r$renames)
  fixed <- \(col, value) {
    source <- src(cols[[col]])
    if (is.null(value)) source else if (is.null(source)) value else rlang::expr(dplyr::coalesce(as.character(!!source), !!value))
  }
  splitter <- \(kind) if (kind == "iqr") quote(bayesmaDatR::split_iqr) else quote(bayesmaDatR::split_range)
  args <- list(study_id = section_id_expr(r, id_fields(cols)), outcome_id = fixed("outcome_id", b$outcome_id),
               outcome_name = src(cols$outcome_name), timepoint = fixed("timepoint", b$timepoint),
               measure = outcome_type_measure(b$type), int_arm = src(cols$int_arm),
               ctrl_arm = src(cols$ctrl_arm))
  for (col in outcome_type_columns(b$type)) {
    own <- cols[[col]]
    inherited <- if (col %in% study_default_columns() && (length(own) || col %in% c("n_int", "n_ctrl"))) study[[col]]
    expr <- src(c(own, inherited))
    parts <- stringr::str_match(col, "^(q1|q3|min|max)_(int|ctrl)$")
    if (!is.na(parts[1])) {
      kind <- if (parts[2] %in% c("q1", "q3")) "iqr" else "range"
      combined <- cols[[paste0(kind, "_", parts[3])]]
      pair_names <- paste0(if (kind == "iqr") c("q1_", "q3_") else c("min_", "max_"), parts[3])
      if (length(combined) && !any(lengths(cols[pair_names]))) {
        if (col == pair_names[1]) {
          args[[paste0(".split_", col)]] <- rlang::call2(splitter(kind), src(combined), names = str2lang(deparse_atomic(pair_names)))
        }
        next
      }
      if (length(combined)) {
        part <- if (kind == "iqr") c("q1", "q3") else c("min", "max")
        split <- rlang::call2("$", rlang::call2(splitter(kind), src(combined)),
                              rlang::sym(part[match(col, pair_names)]))
        expr <- if (is.null(expr)) split else rlang::expr(dplyr::coalesce(!!expr, !!split))
      }
    }
    args[[col]] <- expr
  }
  args <- purrr::compact(args)
  split_cols <- purrr::imap(args, \(value, name) {
    if (startsWith(name, ".split_")) eval(rlang::call_args(value)$names) else name
  })
  stages <- list(transmute_lines(args))
  missing_ids <- c(if (!(isTRUE(r$wrangle) && r$filtered && identical(id_fields(cols), r$ids))) "is.na(study_id)",
                   if (!is.null(cols$outcome_id)) "is.na(outcome_id)")
  if (length(missing_ids)) stages <- c(stages, list(paste0("dplyr::filter_out(", paste(missing_ids, collapse = " | "), ")")))
  data_cols <- intersect(outcome_data_columns(b$type), unlist(split_cols))
  if (length(data_cols)) {
    stages <- c(stages, list(flow_text(paste0("dplyr::filter_out(dplyr::if_all(c(",
                                              paste(sym_text(data_cols), collapse = ", "), "), is.na))"))))
  }
  structure(stages, columns = unlist(split_cols, use.names = FALSE))
}

