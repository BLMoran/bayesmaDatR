row_condition <- function(df, section, row) {
  fallback <- rlang::expr(dplyr::row_number() == !!as.numeric(row))
  keys <- intersect(section_keys(section), names(df))
  if (!length(keys) || is.na(df$study_id[row])) return(fallback)
  for (n in seq_along(keys)) {
    used <- keys[seq_len(n)]
    match <- purrr::reduce(used, \(acc, k) acc & df[[k]] %in% df[[k]][row], .init = rep(TRUE, nrow(df)))
    if (sum(match) == 1) {
      conds <- purrr::map(used, \(k) {
        value <- df[[k]][row]
        if (is.na(value)) rlang::expr(is.na(!!rlang::sym(k))) else rlang::expr(!!rlang::sym(k) == !!value)
      })
      return(purrr::reduce(conds, \(a, b) rlang::expr(!!a & !!b)))
    }
  }
  fallback
}

cell_literal <- function(value, column) {
  if (is.na(value)) return(NA)
  number <- suppressWarnings(as.numeric(value))
  if (!is.na(number) && (is.numeric(column) || all(is.na(column)))) number else value
}

tidy_op <- function(step, before, after, ctx) {
  args <- step$args
  section <- args[[1]]
  if (step$fn == "import_study_column") section <- "studies"
  defined <- section %in% ctx$defined
  op <- \(stage, type = "call") list(table = section, type = type, stage = stage)

  switch(step$fn,
    edit_ma_cells = {
      df <- before[[section]]
      edits <- data.frame(row = args$row, column = args$column, value = as.character(args$value))
      edits <- edits[order(edits$column %in% section_keys(section)), , drop = FALSE]
      lines <- purrr::pmap_chr(edits, \(row, column, value) {
        cond <- row_condition(df, section, row)
        new_value <- cell_literal(value, df[[column]])
        known <- ctx$columns[[section]]
        edit <- if (is.null(known) || column %in% known) {
          rlang::expr(replace(!!rlang::sym(column), !!cond, !!new_value))
        } else {
          rlang::expr(dplyr::if_else(!!cond, !!new_value, NA))
        }
        if (!is.null(known)) ctx$columns[[section]] <- union(known, column)
        paste(sym_text(column), "=", expr_text(edit))
      })
      if (section == "studies") {
        changed <- setdiff(edits$row, edits$row[edits$column == "study_id"])
        changed <- changed[!purrr::map2_lgl(before$studies$study_id[changed], after$studies$study_id[changed], identical)]
        lines <- c(lines, purrr::map_chr(changed, \(row) {
          cond <- row_condition(df, section, row)
          paste("study_id =", expr_text(rlang::expr(replace(study_id, !!cond, !!after$studies$study_id[row]))))
        }))
      }
      op(lines, "mutate")
    },
    add_ma_rows = {
      values <- args[-1]
      values$.n <- NULL
      n <- args$.n %||% max(1L, lengths(values))
      if (!length(values)) values <- list(study_id = rep(NA_character_, n))
      call <- rlang::expr_deparse(rlang::call2(quote(tibble::tibble), !!!purrr::map(values, \(v) str2lang(deparse_atomic(v)))),
                                  width = 76)
      ctx$defined <- union(ctx$defined, section)
      ctx$columns[[section]] <- union(if (defined) ctx$columns[[section]] else character(), names(values))
      list(table = section, type = "call", stage = wrap_call("dplyr::bind_rows", call), new = !defined)
    },
    remove_ma_rows = {
      if (!defined) return(NULL)
      cond <- args[[2]]
      if (isTRUE(cond)) return(op("dplyr::slice(0)"))
      rows <- if (rlang::is_call(cond, "%in%") && rlang::is_call(cond[[2]], "row_number", ns = "dplyr")) eval(cond[[3]])
      if (!is.null(rows)) {
        conds <- purrr::map(rows, \(r) row_condition(before[[section]], section, r))
        by_key <- !purrr::some(conds, \(c) rlang::is_call(c, "==") && rlang::is_call(c[[2]], "row_number", ns = "dplyr"))
        if (by_key) {
          cond <- if (length(conds) == 1) conds[[1]] else rlang::call2(quote(dplyr::when_any), !!!conds)
        }
      }
      op(paste0("dplyr::filter_out(", expr_text(cond), ")"))
    },
    modify_ma_columns = {
      if (!defined) return(NULL)
      known <- ctx$columns[[section]]
      if (!is.null(known)) {
        known <- setdiff(union(known, args$add), args$drop)
        known[match(args$rename, known, nomatch = 0)] <- names(args$rename)[args$rename %in% known]
        ctx$columns[[section]] <- known
      }
      stages <- list()
      if (length(args$add)) {
        stages <- c(stages, list(paste0("dplyr::mutate(", paste(sym_text(args$add), "= NA", collapse = ", "), ")")))
      }
      if (length(args$types)) {
        convert <- c(text = "as.character", integer = "as.integer", numeric = "as.numeric", date = "as.Date")
        stages <- c(stages, list(paste0("dplyr::mutate(", paste0(sym_text(names(args$types)), " = ",
                                                              convert[args$types], "(", sym_text(names(args$types)), ")",
                                                              collapse = ", "), ")")))
      }
      if (length(args$drop)) {
        dropped <- if (length(args$drop) == 1) sym_text(args$drop) else paste0("c(", paste(sym_text(args$drop), collapse = ", "), ")")
        stages <- c(stages, list(paste0("dplyr::select(-", dropped, ")")))
      }
      if (length(args$rename)) {
        stages <- c(stages, list(paste0("dplyr::rename(", paste(sym_text(names(args$rename)), "=", sym_text(args$rename),
                                                            collapse = ", "), ")")))
      }
      list(table = section, type = "stages", stage = stages)
    },
    sync_ma_section = {
      b <- before[[section]]
      a <- after[[section]]
      added <- if (section == "outcomes") {
        a[!paste(a$study_id, a$outcome_id) %in% paste(b$study_id, b$outcome_id), , drop = FALSE]
      } else {
        a[seq_len(nrow(a)) > nrow(b), , drop = FALSE]
      }
      if (!nrow(added)) return(NULL)
      if (section == "risk_of_bias") {
        known <- match(added$study_id, after$studies$study_id)
        for (col in intersect(c("year", "author"), names(after$studies))) {
          added <- tibble::add_column(added, !!col := after$studies[[col]][known], .after = "study_id")
        }
      }
      added <- added[setdiff(names(added)[purrr::map_lgl(added, \(x) any(!is.na(x)))], "design_effect")]
      stages <- list(wrap_call("dplyr::bind_rows", tibble_call(added)))
      if (section == "outcomes") {
        order <- rlang::expr(dplyr::arrange(match(outcome_id, !!unique(stats::na.omit(b$outcome_id))),
                                            match(study_id, !!unique(before$studies$study_id[!is_blank(before$studies$study_id)]))))
        stages <- c(stages, list(rlang::expr_deparse(order, width = 76)))
      }
      ctx$defined <- union(ctx$defined, section)
      ctx$columns[[section]] <- union(if (defined) ctx$columns[[section]] else character(), names(added))
      list(table = section, type = "stages", stage = stages, new = !defined,
           comment = paste("Add every study missing from", section_label(section)))
    },
    import_study_column = {
      r <- raw_info(ctx, args$path, args$sheet %||% 1, args$header_row %||% 1)
      raw <- r$name
      id <- section_id_expr(r, id_fields(as.list(args$keys %||% c(study_id = "study_id"))))
      name <- args$name %||% args$source
      if (!is.null(ctx$columns$studies)) ctx$columns$studies <- union(ctx$columns$studies, name)
      inner <- assign_pipe(NULL, raw, list(
        transmute_lines(c(list(study_id = id), stats::setNames(list(rlang::sym(args$source)), name))),
        "dplyr::filter_out(is.na(study_id))",
        "dplyr::distinct(study_id, .keep_all = TRUE)"
      ))
      op(c("dplyr::left_join(", paste0("  ", inner[-length(inner)]), paste0("  ", inner[length(inner)], ","),
           "  by = dplyr::join_by(study_id)", ")"))
    },
    NULL
  )
}

emit_ops <- function(ops, ctx) {
  groups <- list()
  for (op in ops) {
    last <- if (length(groups)) groups[[length(groups)]] else NULL
    if (!is.null(last) && last$table == op$table && !isTRUE(op$new) && is.null(op$comment) && is.null(last$comment)) {
      groups[[length(groups)]]$ops <- c(last$ops, list(op))
    } else {
      groups <- c(groups, list(list(table = op$table, ops = list(op), new = isTRUE(op$new), comment = op$comment)))
    }
  }
  unlist(purrr::map(groups, \(g) {
    stages <- list()
    for (op in g$ops) {
      if (op$type == "mutate" && length(stages) && isTRUE(attr(stages[[length(stages)]], "mutate"))) {
        args <- c(attr(stages[[length(stages)]], "args"), op$stage)
        stages[[length(stages)]] <- mutate_stage(args)
      } else if (op$type == "mutate") {
        stages <- c(stages, list(mutate_stage(op$stage)))
      } else if (op$type == "stages") {
        stages <- c(stages, op$stage)
      } else {
        stages <- c(stages, list(op$stage))
      }
    }
    source <- if (g$new) "tibble::tibble()" else table_var(g$table)
    c("", paste0("# ", g$comment %||% paste("Edits made in the app:", section_label(g$table))),
      assign_pipe(table_var(g$table), source, stages))
  }))
}

mutate_stage <- function(args) {
  lines <- c("dplyr::mutate(", paste0("  ", args, c(rep(",", length(args) - 1), "")), ")")
  structure(lines, mutate = TRUE, args = args)
}

transmute_lines <- function(args) {
  items <- purrr::imap_chr(args, \(value, name) {
    text <- expr_text(value, width = if (startsWith(name, ".split_")) 90 else 76)
    if (identical(text, sym_text(name)) || startsWith(name, ".split_")) text else paste(sym_text(name), "=", text)
  })
  items <- stringr::str_replace_all(items, "\n", "\n  ")
  c("dplyr::transmute(", paste0("  ", items, c(rep(",", length(items) - 1), "")), ")")
}

assign_pipe <- function(target, source, stages) {
  body <- purrr::imap(stages, \(lines, i) {
    lines <- paste0("  ", unlist(strsplit(paste(lines, collapse = "\n"), "\n")))
    if (i < length(stages)) lines[length(lines)] <- paste(lines[length(lines)], "|>")
    lines
  }) |>
    unlist()
  c(paste0(if (!is.null(target)) paste(target, "<- "), source, " |>"), body)
}

wrap_call <- function(fn, inner) {
  if (length(inner) == 1 && nchar(inner) < 60) return(paste0(fn, "(", inner, ")"))
  c(paste0(fn, "("), paste0("  ", inner), ")")
}

tibble_call <- function(df) {
  values <- purrr::map(as.list(df), \(x) {
    x <- unname(x)
    if (length(x) > 1 && length(unique(x)) == 1) x <- x[1]
    str2lang(deparse_atomic(x))
  })
  lines <- paste0("  ", sym_text(names(values)), " = ", purrr::map_chr(values, expr_text))
  c("tibble::tibble(", paste0(lines, c(rep(",", length(lines) - 1), "")), ")")
}

expr_text <- function(x, width = 76) {
  if (!rlang::is_call(x) && !rlang::is_symbol(x)) return(deparse_atomic(x))
  flat <- paste(rlang::expr_deparse(x, width = 500L), collapse = " ")
  if (nchar(flat) <= width || !rlang::is_call(x)) return(flat)
  head <- paste(rlang::expr_deparse(x[[1]]), collapse = "")
  args <- rlang::call_args(x)
  if (!length(args) || !grepl("^[A-Za-z.][A-Za-z0-9._:]*$", head)) return(flat)
  nms <- names(args) %||% rep("", length(args))
  items <- purrr::map2_chr(args, nms, \(a, nm) {
    paste0(if (nzchar(nm)) paste(sym_text(nm), "= "), expr_text(a, width - 2))
  })
  items <- stringr::str_replace_all(items, "\n", "\n  ")
  paste0(head, "(\n", paste0("  ", items, collapse = ",\n"), "\n)")
}

sym_text <- function(x) {
  purrr::map_chr(x, \(nm) if (make.names(nm) == nm) nm else paste0("`", nm, "`"))
}

check_tidy_script <- function(lines, files, expected, result = attr(lines, "result")) {
  dir <- tempfile("bayesmaDatR_check_")
  dir.create(dir)
  on.exit(unlink(dir, recursive = TRUE), add = TRUE)
  purrr::iwalk(files, \(path, name) file.copy(path, file.path(dir, name)))
  old <- setwd(dir)
  on.exit(setwd(old), add = TRUE, after = FALSE)
  lines[startsWith(lines, "data_dir <- ")] <- "data_dir <- \".\""
  env <- new.env(parent = globalenv())
  result <- tryCatch(
    suppressMessages(suppressWarnings({
      eval(parse(text = lines), envir = env)
      env[[result %||% "ma_data"]]
    })),
    error = function(e) e
  )
  if (inherits(result, "error")) return(conditionMessage(result))
  filled <- \(df) {
    df <- as.data.frame(df)
    df[purrr::map_lgl(df, \(x) any(!is.na(x)))]
  }
  result <- filled(result)
  expected <- filled(expected)
  same <- setequal(names(result), names(expected)) &&
    isTRUE(all.equal(result[names(expected)], expected, check.attributes = FALSE))
  if (same) TRUE else "its result differs from the app's"
}

